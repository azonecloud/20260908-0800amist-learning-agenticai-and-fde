# Numeric Types:
# - int: Integers, e.g., 42, -10, 0.
# - float: Floating-point numbers, e.g., 3.14, -2.5, 0.0.
# - complex: Complex numbers, e.g., 3+2j, -1+4j.

# Text Type:
# - str: Strings of characters, e.g., "Hello, Python!", '123', "Data Science".

# Sequence Types:
# - list: Ordered, mutable collections of elements.
# - tuple: Ordered, immutable collections of elements.

# Set Types:
# - set: Unordered, mutable collections of unique elements.
# - frozenset: Unordered, immutable collections of unique elements.

# Mapping Type:
# - dict: Collection of key-value pairs.

# Boolean Type:
# - bool: Represents the truth values True or False.


# int
x = 101
print(type(x))

# float
f = 3.14
print(type(f))

# complex
c = 3 + 2j
print(type(c))

# str
y = "Hello, Python!"
print(type(y))

# list
z = [1, 2, 3]
print(type(z))

# tuple
t = (1, 2, 3)
print(type(t))

# set
s = {1, 2, 3}
print(type(s))

# frozenset
fs = frozenset({1, 2, 3})
print(type(fs))

# bool
b = True
print(type(b))

# dict
d = {'name': 'John', 'age': 100}
print(type(d))

# Access dictionary value
print(d['name'])
